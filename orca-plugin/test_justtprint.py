HERE = os.path.dirname(os.path.abspath(__file__))


def fake_orca():
    orca = types.ModuleType("orca")

    class Base:
        def __init__(self):
            self.config = None
            self.posted = []

        def get_config(self):
            return self.config or "{}"

        def save_config(self, text):
            json.loads(text)
            self.config = text
            return True

        def post_message(self, data):
            self.posted.append(json.loads(json.dumps(data)))

    orca.base = Base
    orca.plugin = lambda cls: cls
    orca.registered = []
    orca.register_capability = orca.registered.append
    orca.pages = types.SimpleNamespace(PagesPluginCapabilityBase=Base)

    class Step(enum.Enum):
        posSlice = 0
        psGCodePostProcess = 1

    class Result:
        def __init__(self, kind, message=""):
            self.kind, self.message = kind, message

    orca.slicing = types.SimpleNamespace(SlicingPipelineCapabilityBase=Base, Step=Step)
    orca.ExecutionResult = types.SimpleNamespace(success=lambda message="", data="": Result("success", message), skipped=lambda message="": Result("skipped", message))
    orca.LifecycleEvent = enum.Enum("LifecycleEvent", "NewProject ProjectOpened ProjectAfterSave ProjectClosed GCodeExportFinished SliceStarted DeviceSelected PrintJobStarted PrintJobFinished UploadFinished SendJobFinished")
    orca.LifecycleEvtCode = enum.Enum("LifecycleEvtCode", "Ok Error Warn")
    orca.notifications = []
    orca.answers = []

    class Preset:
        def __init__(self, name, values):
            self.name, self._values = name, values

        def config_value(self, key):
            return self._values.get(key)

    orca.Preset = Preset
    orca.presets = []
    orca.project = {}
    orca.host = types.SimpleNamespace(
        preset_bundle=lambda: types.SimpleNamespace(
            current_filament_presets=lambda: orca.presets, full_config_value=lambda key: orca.project.get(key)
        ),
        plater=lambda: types.SimpleNamespace(is_project_dirty=lambda: False),
        ui=types.SimpleNamespace(
            push_notification=lambda level, text, *a, **k: orca.notifications.append((level, text)),
            message=lambda text, **k: orca.answers.pop(0) if orca.answers else "yes",
        ),
    )
    return orca


def load_plugin(orca):
    sys.modules["orca"] = orca
    try:
        spec = importlib.util.spec_from_file_location("justtprint_under_test", os.path.join(HERE, "justtprint.py"))
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module
    finally:
        del sys.modules["orca"]


