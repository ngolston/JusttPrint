"""Tests for the JusttPrint plugin for OrcaSlicer (justtprint.py), outside OrcaSlicer.

A stand-in `orca` module takes OrcaSlicer's place and a small HTTP server JusttPrint's, so the
helpers, the client and the tab's messages are checked without either. Run:

    python3 -I -m unittest discover -s orca-plugin -p "test_*.py"
"""

