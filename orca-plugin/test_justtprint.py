    def test_exports_are_sent_by_hand_or_automatically(self):
        self.connect()
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "Gear.gcode.3mf")
            with open(path, "wb") as f:
                f.write(b"PK")
            ctx = types.SimpleNamespace(name="Gear", msg=path, code=self.orca.LifecycleEvtCode.Ok)
            self.page.on_lifecycle_event(self.orca.LifecycleEvent.GCodeExportFinished, ctx)
            self.page.on_message({"type": "poll"})  # Auto-send is off: nothing sent.
            self.assertFalse(any(c[1].startswith("/api/orca/sliced") for c in FakeJusttPrint.calls))
            self.page.on_message({"type": "send-sliced"})
            self.assertIn("Filed with Gear", self.jp.STATE["last_export"]["result"])

            self.page.on_message({"type": "save-settings", "server": self.address, "api_key": "", "auto_send": True, "verify_tls": True})
            self.page.on_lifecycle_event(self.orca.LifecycleEvent.GCodeExportFinished, ctx)
            FakeJusttPrint.calls.clear()
            self.page.on_message({"type": "poll"})
            self.assertTrue(any(c[1].startswith("/api/orca/sliced") for c in FakeJusttPrint.calls))
            self.page.on_message({"type": "poll"})  # Sent once only.
            self.assertEqual(sum(c[1].startswith("/api/orca/sliced") for c in FakeJusttPrint.calls), 1)

    def test_new_exports_in_the_export_folder_are_found(self):
        with tempfile.TemporaryDirectory() as tmp:
            self.page.on_message({"type": "save-settings", "server": self.address, "api_key": "jpk_good", "auto_send": True, "export_folder": tmp})
            self.assertEqual(json.loads(self.page.config)["export_folder"], tmp)
            self.page._started = __import__("time").time() - 100  # the plugin started a while ago
            old = os.path.join(tmp, "Old.gcode.3mf")
            with open(old, "wb") as f:
                f.write(b"PK")
            os.utime(old, (self.page._started - 60, self.page._started - 60))
            fresh = os.path.join(tmp, "Gear_plate_1.gcode.3mf")
            with open(fresh, "wb") as f:
                f.write(b"PK")
            later = self.page._started + 50
            os.utime(fresh, (later, later))
            with open(os.path.join(tmp, "Gear.gcode"), "w") as f:
                f.write("G28")
            # Still being written (just changed): not yet.
            self.assertIsNone(self.jp.newest_export(tmp, self.page._started, later + 1))
            self.assertEqual(self.jp.newest_export(tmp, self.page._started, later + 10), (fresh, later))
            FakeJusttPrint.calls.clear()
            self.page.on_message({"type": "poll"})
            self.assertEqual(self.jp.STATE["last_export"]["path"], fresh)
            self.assertEqual(sum(c[1].startswith("/api/orca/sliced") for c in FakeJusttPrint.calls), 1, "auto-sent once")
            self.page.on_message({"type": "poll"})
            self.assertEqual(sum(c[1].startswith("/api/orca/sliced") for c in FakeJusttPrint.calls), 1, "and not again")
        with self.assertRaises(Exception):
            self.page._save_settings({"server": self.address, "export_folder": "/no/such/folder"})

