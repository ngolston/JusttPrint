class FakeJusttPrint(http.server.BaseHTTPRequestHandler):
    """Answers the plugin routes the way src/server/orca-plugin.js does."""

    calls = []
    server_version = "10.21.0"

    def log_message(self, *args):
        pass

    def _send(self, status, body):
        raw = json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def _body(self):
        return self.rfile.read(int(self.headers.get("Content-Length") or 0))

    def do_GET(self):
        self._handle("GET")

    def do_POST(self):
        self._handle("POST")

    def _handle(self, method):
        body = self._body() if method == "POST" else b""
        FakeJusttPrint.calls.append((method, self.path, self.headers.get("Authorization"), body))
        if self.headers.get("Authorization") != "Bearer jpk_good":
            return self._send(401, {"error": "Login required"})
        path = self.path.split("?")[0]
        if path == "/api/orca/hello":
            return self._send(
                200,
                {"version": FakeJusttPrint.server_version, "pluginVersion": "9.9.0", "username": "ace", "role": "editor", "slicedInbox": True, "uploadFolder": True},
            )
        if path == "/api/orca/plugin.py":
            raw = b'PLUGIN_VERSION = "9.9.0"\n'
            self.send_response(200)
            self.send_header("Content-Length", str(len(raw)))
            self.end_headers()
            return self.wfile.write(raw)
        if path == "/api/orca/models":
            q = urllib.parse.parse_qs(urllib.parse.urlsplit(self.path).query)
            gear = {"id": 3, "name": "Gear", "fileName": "Gear.3mf", "designer": None, "fileType": "3mf", "thumbnail": None}
            offset = int(q.get("offset", ["0"])[0])
            return self._send(200, {"models": [] if offset else [gear], "total": 1, "offset": offset})
        if path == "/api/orca/spools":
            return self._send(200, {"spools": [{"id": 1, "name": "White PLA", "material": "PLA", "colors": ["#ffffff"], "remaining": 100, "initial": 1000}]})
        if path == "/api/orca/filters":
            return self._send(200, {"tags": [{"name": "gears", "count": 1}], "categories": [], "favorites": 0})
        if path in ("/api/orca/models/3/edit", "/api/orca/models/3/log-print"):
            sent = json.loads(body)
            return self._send(200, {"model": {"id": 3, "name": "Gear", "rating": sent.get("rating", 0), "history": [], "page": "#/model/x"}})
        if path in ("/api/orca/spools/1/weigh", "/api/orca/spools/1/drying"):
            sent = json.loads(body)
            if sent.get("weight") == -1:
                return self._send(400, {"error": "Enter what the scale shows (grams)"})
            return self._send(200, {"spool": {"id": 1, "name": "White PLA", "remaining": sent.get("weight", 100), "weighings": [], "page": "#/filament"}})
        if path == "/api/orca/models/3":
            return self._send(200, {"model": {"id": 3, "name": "Gear", "designer": "Ana", "history": [], "page": "#/model/%2Fm%2FGear.3mf"}})
        if path == "/api/orca/models/4":
            return self._send(404, {"error": "That model is not in the library any more"})
        if path == "/api/orca/spools/1":
            return self._send(200, {"spool": {"id": 1, "name": "White PLA", "remaining": 100, "weighings": [], "page": "#/filament"}})
        if path == "/api/orca/models/3/open":
            return self._send(200, {"modelId": 3, "links": [{"name": "Gear.3mf", "path": "/api/slicer-file/tok/Gear.3mf"}]})
        if path == "/api/orca/filament-check":
            needs = json.loads(body)["needs"]
            return self._send(200, {"spools": 2, "ready": True, "missing": [], "needs": [{**n, "ok": True, "left": 100} for n in needs]})
        if path == "/api/orca/printers":
            return self._send(200, {"printers": [{"id": 1, "name": "MK4", "serial": None, "logsItself": False, "direct": None, "units": []}]})
        if path == "/api/orca/printers/load":
            sent = json.loads(body)
            return self._send(200, {"printers": [{"id": 1, "name": "MK4", "direct": {"id": sent["spoolId"], "name": "White PLA"}, "units": []}]})
        if path == "/api/orca/print-started":
            sent = json.loads(body)
            if sent["deviceId"] == "X1C-SERIAL":
                return self._send(200, {"status": "auto", "printer": {"id": 2, "name": "X1C"}, "model": None, "used": [], "missing": []})
            used = [{"spoolId": 1, "name": "White PLA", "color": "#ffffff", "grams": n["grams"], "left": 80} for n in sent["needs"]]
            return self._send(200, {"status": "taken", "eventId": 7 if sent["modelId"] else None, "used": used, "missing": [], "model": None, "printer": None})
        if path == "/api/orca/print-started/undo":
            return self._send(200, {"undone": True})
        if path == "/api/orca/sliced":
            return self._send(200, {"fileName": "Gear.gcode.3mf", "status": "filed", "model": {"id": 3, "name": "Gear"}})
        if path == "/api/orca/project":
            return self._send(200, {"fileName": "Gear.3mf", "filePath": "/lib/Uploads/Gear.3mf", "added": True})
        if path == "/api/orca/empty":
            self.send_response(200)
            self.send_header("Content-Length", "0")
            self.end_headers()
            return None
        if path == "/api/orca/missing":
            return self._send(400, {"error": "Not a plain file name: x"})
        self.send_response(404)
        self.send_header("Content-Length", "0")
        self.end_headers()


class HelperTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        sys.modules.pop("orca", None)
        spec = importlib.util.spec_from_file_location("justtprint_plain", os.path.join(HERE, "justtprint.py"))
        cls.jp = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(cls.jp)

    def test_versions(self):
        self.assertTrue(self.jp.is_newer("10.20.0", "10.9.3"))
        self.assertFalse(self.jp.is_newer("1.3.0", "1.3.0"))
        self.assertFalse(self.jp.is_newer("dev", "1.0.0"))
        self.assertEqual(self.jp.version_notices({"version": self.jp.MIN_SERVER_VERSION, "pluginVersion": self.jp.PLUGIN_VERSION}), {})
        self.assertEqual(self.jp.version_notices({"version": "10.18.0"}), {"serverTooOld": self.jp.MIN_SERVER_VERSION})
        # The header OrcaSlicer reads and the constant the server reads agree.
        with open(self.jp.__file__, encoding="utf-8") as f:
            self.assertIn(f'# version = "{self.jp.PLUGIN_VERSION}"', f.read())

    def test_server_addresses(self):
        self.assertEqual(self.jp.normalize_server("nas.local:5000"), "http://nas.local:5000")
        self.assertEqual(self.jp.normalize_server(" https://jp.example.com/library/ "), "https://jp.example.com")
        self.assertEqual(self.jp.normalize_server(""), "")
        with self.assertRaises(ValueError):
            self.jp.normalize_server("ftp://nas")

    def test_open_link_is_what_orcaslicer_expects(self):
        link = self.jp.orca_open_link("nas:5000", "/api/slicer-file/abc/Gear%20v2.3mf")
        self.assertEqual(link, "orcaslicer://open?file=http%3A%2F%2Fnas%3A5000%2Fapi%2Fslicer-file%2Fabc%2FGear%2520v2.3mf")

    def test_filaments_from_gcode(self):
        filaments = self.jp.filaments_from_gcode(GCODE)
        self.assertEqual(
            filaments,
            [
                {"slot": 1, "material": "PLA", "color": "#ffffff", "grams": 12.3, "preset": "Bambu PLA Basic"},
                {"slot": 3, "material": "PLA", "color": "#ff0000", "grams": 2.5, "preset": "Bambu PLA Basic"},
            ],
        )

    def test_reads_only_the_ends_of_a_large_file(self):
        with tempfile.NamedTemporaryFile("w", suffix=".gcode", delete=False) as f:
            f.write("; filament_type = PLA\n")
            f.write("G1 X1 Y1\n" * 300000)
            f.write("; filament used [g] = 7.5\n")
            name = f.name
        try:
            text = self.jp.read_gcode_ends(name)
            self.assertLess(len(text), 2 * 1024 * 1024)
            self.assertEqual(self.jp.filaments_from_gcode(text), [{"slot": 1, "material": "PLA", "color": None, "grams": 7.5, "preset": None}])
        finally:
            os.unlink(name)

    def test_needs_from_presets_and_last_slice(self):
        Preset = fake_orca().Preset
        presets = [Preset("Bambu PLA Basic", {"filament_type": ["PLA"], "filament_colour": ["#FFFFFF"]}), None, Preset("Generic PETG", {"filament_type": "PETG", "filament_colour": "#000000"})]
        self.assertEqual(
            self.jp.needs_from_presets(presets),
            [
                {"slot": 1, "material": "PLA", "color": "#ffffff", "grams": None, "preset": "Bambu PLA Basic"},
                {"slot": 3, "material": "PETG", "color": "#000000", "grams": None, "preset": "Generic PETG"},
            ],
        )
        # After a slice: only what it used, with its grams.
        last = {"filaments": [{"slot": 1, "material": "PLA", "color": "#ffffff", "grams": 12.3, "preset": "Bambu PLA Basic"}]}
        self.assertEqual(self.jp.needs_from_presets(presets, last), [{"slot": 1, "material": "PLA", "color": "#ffffff", "grams": 12.3, "preset": "Bambu PLA Basic"}])
        # No presets (older OrcaSlicer): the slice's own list.
        self.assertEqual(self.jp.needs_from_presets([], last), last["filaments"])


class WithServer(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), FakeJusttPrint)
        threading.Thread(target=cls.server.serve_forever, daemon=True).start()
        cls.address = f"http://127.0.0.1:{cls.server.server_address[1]}"

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()

    def setUp(self):
        FakeJusttPrint.calls.clear()


class ClientTests(WithServer):
    def setUp(self):
        super().setUp()
        self.orca = fake_orca()
        self.jp = load_plugin(self.orca)

    def test_needs_an_address_and_a_key(self):
        with self.assertRaises(self.jp.JusttPrintError):
            self.jp.Client("", "jpk_good")
        with self.assertRaises(self.jp.JusttPrintError):
            self.jp.Client(self.address, "")

    def test_signs_in_with_the_api_key(self):
        client = self.jp.Client(self.address, "jpk_good")
        self.assertEqual(client.hello()["username"], "ace")
        self.assertEqual(FakeJusttPrint.calls[0][2], "Bearer jpk_good")

    def test_errors_say_what_to_do(self):
        with self.assertRaisesRegex(self.jp.JusttPrintError, "API key"):
            self.jp.Client(self.address, "jpk_bad").hello()
        with self.assertRaisesRegex(self.jp.JusttPrintError, "Not a plain file name"):
            self.jp.Client(self.address, "jpk_good").request("POST", "/api/orca/missing", body={})
        with self.assertRaisesRegex(self.jp.JusttPrintError, "Update JusttPrint"):
            self.jp.Client(self.address, "jpk_good").request("GET", "/api/orca/nothing")
        with self.assertRaisesRegex(self.jp.JusttPrintError, "cannot read"):
            self.jp.Client(self.address, "jpk_good").request("GET", "/api/orca/empty")
        with self.assertRaisesRegex(self.jp.JusttPrintError, "Could not reach"):
            self.jp.Client("http://127.0.0.1:9", "jpk_good").hello()

    def test_uploads_stream_the_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "Gear plate 1.gcode.3mf")
            with open(path, "wb") as f:
                f.write(b"PK sliced bytes")
            result = self.jp.Client(self.address, "jpk_good").send_sliced(path, 3)
        self.assertEqual(result["status"], "filed")
        method, url, _, body = FakeJusttPrint.calls[-1]
        self.assertEqual((method, body), ("POST", b"PK sliced bytes"))
        self.assertIn("name=Gear+plate+1.gcode.3mf", url)
        self.assertIn("modelId=3", url)


class PageTests(WithServer):
    def setUp(self):
        super().setUp()
        self.orca = fake_orca()
        self.jp = load_plugin(self.orca)
        self.opened = []
        self.jp.open_with_system = self.opened.append
        for key in self.jp.STATE:
            self.jp.STATE[key] = None
        self.page = self.jp.JusttPrintPage()

    def posted(self, kind):
        return [m for m in self.page.posted if m.get("type") == kind]

    def connect(self):
        self.page.on_message({"type": "save-settings", "server": self.address, "api_key": "jpk_good", "auto_send": False, "verify_tls": True})

    def test_registers_both_capabilities(self):
        self.jp.JusttPrintPlugin().register_capabilities()
        self.assertEqual(self.orca.registered, [self.jp.JusttPrintPage])

    def test_settings_are_saved_and_the_key_is_never_sent_to_the_page(self):
        self.connect()
        saved = json.loads(self.page.config)
        self.assertEqual(saved["api_key"], "jpk_good")
        state = self.posted("state")[-1]
        self.assertTrue(state["connection"]["ok"])
        self.assertTrue(state["settings"]["has_key"])
        self.assertNotIn("jpk_good", json.dumps(self.page.posted))
        # Saving again with an empty key keeps the saved one.
        self.page.on_message({"type": "save-settings", "server": self.address, "api_key": "", "auto_send": True})
        self.assertEqual(json.loads(self.page.config)["api_key"], "jpk_good")

    def test_without_settings_the_page_says_what_to_do(self):
        self.page.on_message({"type": "search", "q": "gear"})
        self.assertIn("server address", self.posted("toast")[-1]["text"])

    def test_search_and_open_on_the_plate(self):
        self.connect()
        self.page.on_message({"type": "search", "q": "gear"})
        self.assertEqual(self.posted("models")[-1]["models"][0]["name"], "Gear")
        # The library tab asks for a page at a time (tagged, so a new search drops old answers), with its filter and sort.
        self.page.on_message({"type": "models", "q": "", "status": "printed", "sort": "name", "offset": 30, "limit": 30, "seq": 4})
        page = self.posted("models")[-1]
        self.assertEqual((page["models"], page["total"], page["offset"], page["seq"]), ([], 1, 30, 4))
        query = urllib.parse.parse_qs(urllib.parse.urlsplit(FakeJusttPrint.calls[-1][1]).query)
        self.assertEqual((query["status"], query["sort"], query["offset"]), (["printed"], ["name"], ["30"]))
        self.page.on_message({"type": "open", "id": 3, "name": "Gear"})
        self.assertEqual(self.opened, [self.jp.orca_open_link(self.address, "/api/slicer-file/tok/Gear.3mf")])
        self.assertEqual(self.jp.STATE["opened_model"], {"id": 3, "name": "Gear"})
        self.assertEqual(self.posted("opened")[-1]["id"], 3)
        self.assertEqual(self.posted("state")[-1]["opened_model"]["id"], 3)

    def test_a_newer_plugin_on_the_server_is_offered_and_downloaded(self):
        self.connect()
        connection = self.posted("state")[-1]["connection"]
        self.assertEqual((connection["pluginUpdate"], connection["pluginVersion"]), ("9.9.0", self.jp.PLUGIN_VERSION))
        self.assertNotIn("serverTooOld", connection)
        with tempfile.TemporaryDirectory() as tmp:
            self.jp.downloads_folder = lambda: tmp
            # Someone else's justtprint.py is kept; an older plugin of ours would be replaced.
            with open(os.path.join(tmp, "justtprint.py"), "w") as f:
                f.write("my notes")
            self.page.on_message({"type": "download-plugin"})
            path = self.posted("plugin-downloaded")[-1]["path"]
            self.assertEqual(path, os.path.join(tmp, "justtprint-9.9.0.py"))
            with open(path, "rb") as f:
                self.assertEqual(f.read(), b'PLUGIN_VERSION = "9.9.0"\n')
            self.assertEqual(self.opened, [tmp])
            os.remove(os.path.join(tmp, "justtprint.py"))
            self.page.on_message({"type": "download-plugin"})
            self.assertEqual(self.posted("plugin-downloaded")[-1]["path"], os.path.join(tmp, "justtprint.py"))
            self.page.on_message({"type": "download-plugin"})
            self.assertEqual(self.posted("plugin-downloaded")[-1]["path"], os.path.join(tmp, "justtprint.py"), "our own plugin file is replaced")

    def test_a_server_too_old_for_the_plugin_is_named(self):
        FakeJusttPrint.server_version = "10.19.0"
        try:
            self.connect()
        finally:
            FakeJusttPrint.server_version = "10.21.0"
        self.assertEqual(self.posted("state")[-1]["connection"]["serverTooOld"], self.jp.MIN_SERVER_VERSION)
        # A route the old server lacks says to update it.
        self.page.on_message({"type": "spool", "id": 5})
        self.assertIn("Update JusttPrint to", self.posted("toast")[-1]["text"])

