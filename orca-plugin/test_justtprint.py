        last = self.posted("state")[-1]["last_print"]
        self.assertEqual((last["status"], last["eventId"], last["undone"]), ("taken", 7, False))
        self.assertTrue(self.orca.notifications)
        # Undo gives it back.
        self.page.on_message({"type": "undo-print"})
        self.assertEqual(json.loads(FakeJusttPrint.calls[-2][3]), {"eventId": 7})
        self.assertTrue(self.jp.STATE["last_print"]["undone"])
