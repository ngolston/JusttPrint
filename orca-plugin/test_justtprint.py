        self.page.on_message({"type": "poll"})
        self.assertIsNone(self.jp.STATE["last_print"], "a failed send takes nothing off")
        self.sent("PrintJobFinished")
        self.page.on_message({"type": "poll"})
        self.page.on_message({"type": "poll"})
        takes = [c for c in FakeJusttPrint.calls if c[1] == "/api/orca/print-started"]
